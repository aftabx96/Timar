/*
  Builds src/lib/coastShapes.js from OpenStreetMap data, so the drawn map on the home page
  traces the real shore at Rehri Goth and the mangrove islands Saltwater Marina works on.

  Usage:  node scripts/build-coast.cjs path/to/osm.json
  Get osm.json from the Overpass API with:
    [out:json];(way["natural"="coastline"](24.69,67.12,24.86,67.32);
    way["wetland"="mangrove"](24.69,67.12,24.86,67.32);
    relation["wetland"="mangrove"](24.69,67.12,24.86,67.32););out geom;
  Map data (c) OpenStreetMap contributors, ODbL.
*/
const fs = require('fs')
const path = require('path')

const VIEW = { w: 67.165, e: 67.29, s: 24.712, n: 24.832 } // the window the drawing shows
const W = 600
const kx = Math.cos((((VIEW.n + VIEW.s) / 2) * Math.PI) / 180) // keeps a kilometre the same both ways
const H = Math.round((W * (VIEW.n - VIEW.s)) / ((VIEW.e - VIEW.w) * kx))
const X = (lon) => ((lon - VIEW.w) / (VIEW.e - VIEW.w)) * W
const Y = (lat) => ((VIEW.n - lat) / (VIEW.n - VIEW.s)) * H

const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
const key = (p) => `${p.lat.toFixed(7)},${p.lon.toFixed(7)}`

// joins line pieces that share end points into the longest possible chains
function stitch(pieces) {
  const chains = pieces.map((p) => p.slice())
  let merged = true
  while (merged) {
    merged = false
    outer: for (let i = 0; i < chains.length; i++) {
      for (let j = 0; j < chains.length; j++) {
        if (i === j) continue
        const a = chains[i]
        const b = chains[j]
        if (key(a.at(-1)) === key(b[0])) chains[i] = a.concat(b.slice(1))
        else if (key(a.at(-1)) === key(b.at(-1))) chains[i] = a.concat(b.slice(0, -1).reverse())
        else if (key(a[0]) === key(b.at(-1))) chains[i] = b.concat(a.slice(1))
        else if (key(a[0]) === key(b[0])) chains[i] = b.slice().reverse().concat(a.slice(1))
        else continue
        chains.splice(j, 1)
        merged = true
        break outer
      }
    }
  }
  return chains
}

// Douglas Peucker in screen space
function simplify(pts, tol) {
  if (pts.length < 3) return pts
  const [a, b] = [pts[0], pts.at(-1)]
  let max = 0
  let idx = 0
  for (let i = 1; i < pts.length - 1; i++) {
    const p = pts[i]
    const dx = b[0] - a[0]
    const dy = b[1] - a[1]
    const d = Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / (Math.hypot(dx, dy) || 1)
    if (d > max) [max, idx] = [d, i]
  }
  if (max <= tol) return [a, b]
  return simplify(pts.slice(0, idx + 1), tol).slice(0, -1).concat(simplify(pts.slice(idx), tol))
}

// a closed ring starts and ends on the same point, which would collapse it; simplify each half instead
function simplifyRing(pts, tol) {
  const mid = Math.floor(pts.length / 2)
  return simplify(pts.slice(0, mid + 1), tol).slice(0, -1).concat(simplify(pts.slice(mid), tol))
}

// keeps only shapes that reach into the drawing
const inView = (pts) => pts.some(([x, y]) => x > -20 && x < W + 20 && y > -20 && y < H + 20)

const toPath = (pts, close) =>
  pts.map((p, i) => `${i ? 'L' : 'M'}${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join('') + (close ? 'Z' : '')

const project = (geom) => geom.map((p) => [X(p.lon), Y(p.lat)])

// mainland: coastline chains that do not close on themselves, closed through the land to the north
const coast = data.elements.filter((e) => e.tags?.natural === 'coastline').map((e) => e.geometry)
const coastChains = stitch(coast)
const land = []
const islands = []
for (const c of coastChains) {
  const closed = key(c[0]) === key(c.at(-1))
  const pts = closed ? simplifyRing(project(c), 0.6) : simplify(project(c), 0.6)
  if (closed && inView(pts)) islands.push(toPath(pts, true))
  else if (!closed) land.push(toPath([...pts, [pts.at(-1)[0], -400], [pts[0][0], -400]], true))
}

// mangrove: ways are rings already; relations are outer pieces that need joining
const mangrove = []
for (const e of data.elements.filter((x) => x.tags?.wetland === 'mangrove')) {
  const rings = e.type === 'way' ? [e.geometry] : stitch(e.members.filter((m) => m.role !== 'inner' && m.geometry).map((m) => m.geometry))
  for (const r of rings) {
    const pts = simplifyRing(project(r), 0.6)
    if (pts.length > 3 && inView(pts)) mangrove.push(toPath(pts, true))
  }
}

const sites = {
  rehri: [24.81444, 67.22889],
  kaderu: [24.778853, 67.241696],
  buddo: [24.733, 67.21],
}
const out = {
  width: W,
  height: H,
  view: VIEW,
  kmPx: +(W / ((VIEW.e - VIEW.w) * 111.32 * kx)).toFixed(3),
  land,
  islands,
  mangrove,
  sites: Object.fromEntries(Object.entries(sites).map(([k, [la, lo]]) => [k, [+X(lo).toFixed(1), +Y(la).toFixed(1)]])),
}

const file = path.join(__dirname, '..', 'src', 'lib', 'coastShapes.js')
fs.writeFileSync(
  file,
  `// Generated by scripts/build-coast.cjs from OpenStreetMap data (c) OpenStreetMap contributors, ODbL. Do not edit by hand.\nexport default ${JSON.stringify(out)}\n`,
)
console.log(`wrote ${file}: ${W}x${H}, land ${land.length}, islands ${islands.length}, mangrove ${mangrove.length}, ${(fs.statSync(file).size / 1024).toFixed(1)} KB`)
